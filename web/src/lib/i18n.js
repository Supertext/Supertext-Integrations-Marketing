/** The string table of a language (plain object, so it can be passed to client components). */
export const strings = (locale) => ({ ...STRINGS.en, ...(STRINGS[locale] || {}) });

/** One string with {placeholder} substitution. */
export const format = (table, key, values = {}) =>
  (table[key] ?? key).replace(/\{(\w+)\}/g, (m, name) => (name in values ? values[name] : m));

/** CMS links are written with /en/…; show them in the reader's language. */
export function localizeHref(url, locale) {
  if (!url) return '#';
  const match = url.match(/^\/(en|de|fr|it)(?=\/|\?|#|$)/);
  if (match) return `/${locale}${url.slice(match[0].length)}`;
  return url;
}

